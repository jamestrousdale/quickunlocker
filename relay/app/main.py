"""pc-unlock relay.

A tiny passkey-gated relay between a locked Windows PC and your phone.

Trust model: this service is a *messenger*. The PC generates the challenge and
verifies the passkey assertion itself against a public key it pinned at
enrollment. A compromised relay can deny service, but cannot unlock the PC.
The relay also verifies assertions (defense in depth) before passing them on.
"""

from __future__ import annotations

import asyncio
import json
import os
import secrets
import socket
import time
from contextlib import suppress
from dataclasses import dataclass, field
from pathlib import Path
from typing import TYPE_CHECKING, Annotated, Any

from credential_store import CredentialStore, matches_pc
from fastapi import FastAPI, HTTPException, Query, Request
from fastapi.responses import FileResponse, JSONResponse, Response
from fastapi.staticfiles import StaticFiles
from pydantic import BaseModel, Field
from relay_webauthn import b64url, b64url_decode, check_authentication, fingerprint, spki_from_cose
from webauthn import (
    generate_registration_options,
    options_to_json,
    verify_registration_response,
)
from webauthn.helpers.cose import COSEAlgorithmIdentifier
from webauthn.helpers.structs import (
    AuthenticatorSelectionCriteria,
    ResidentKeyRequirement,
    UserVerificationRequirement,
)

if TYPE_CHECKING:
    from collections.abc import Awaitable, Callable

# --------------------------------------------------------------------------- config

RP_ID = os.environ.get('RP_ID', 'localhost')
ORIGIN = (os.environ.get('ORIGIN') or f'https://{RP_ID}').rstrip('/')
RP_NAME = os.environ.get('RP_NAME', 'PC Unlock')
DATA_DIR = Path(os.environ.get('DATA_DIR', '/data'))
REQUEST_TTL = int(os.environ.get('REQUEST_TTL', '90'))  # seconds a pending unlock lives
MAX_PENDING = 8
ENROLL_TTL = 300
MAX_ENROLL_SESSIONS = 32
WAKE_BROADCAST = os.environ.get('WAKE_BROADCAST', '255.255.255.255')
WAKE_PC_COOLDOWN = 10.0
WAKE_GLOBAL_COOLDOWN = 1.0
STATIC_DIR = Path(__file__).parent / 'static'
PC_NAME = r'^[A-Za-z0-9][A-Za-z0-9_.-]{0,39}$'
MAC_ADDRESS = r'(?i)^(?:[0-9a-f]{2}:){5}[0-9a-f]{2}$'


@dataclass
class EnrollmentSession:
    phone_id: str
    pc_name: str
    mac: str
    challenge: bytes
    expires: float
    result: dict[str, str] | None = None
    event: asyncio.Event = field(default_factory=asyncio.Event)


@dataclass
class UnlockRequest:
    id: str
    pc_name: str
    challenge: bytes
    created: float
    status: str = 'pending'  # pending | approved | expired
    assertion: dict[str, Any] | None = None
    event: asyncio.Event = field(default_factory=asyncio.Event)

    def expired(self) -> bool:
        return time.time() - self.created > REQUEST_TTL


def send_magic_packet(mac: str) -> None:
    packet = b'\xff' * 6 + bytes.fromhex(mac.replace(':', '')) * 16
    with socket.socket(socket.AF_INET, socket.SOCK_DGRAM) as sock:
        sock.setsockopt(socket.SOL_SOCKET, socket.SO_BROADCAST, 1)
        sock.settimeout(0.0)
        sock.sendto(packet, (WAKE_BROADCAST, 9))


# --------------------------------------------------------------------------- models


class NewEnrollment(BaseModel):
    pc_name: str = Field(pattern=PC_NAME)
    mac: str = Field(pattern=MAC_ADDRESS)


class EnrollmentPhone(BaseModel):
    session: str = Field(min_length=32, max_length=64)


class EnrollFinish(EnrollmentPhone):
    credential: dict[str, Any]


class NewRequest(BaseModel):
    pc_name: str = Field(min_length=1, max_length=40)
    challenge: str  # base64url, generated by the PC


# --------------------------------------------------------------------------- app


class Relay:
    """State shared by the routes of one relay worker."""

    def __init__(self) -> None:
        self.store = CredentialStore(DATA_DIR / 'credentials.json')
        self.requests: dict[str, UnlockRequest] = {}
        self.enroll_sessions: dict[str, EnrollmentSession] = {}
        self.phone_sessions: dict[str, EnrollmentSession] = {}
        self.last_wake: dict[str, float] = {}
        self.last_broadcast = -float('inf')

    def prune(self) -> None:
        for rid in [r for r, req in self.requests.items() if req.expired()]:
            self.requests[rid].status = 'expired'
            self.requests[rid].event.set()
            del self.requests[rid]

    def remove_enrollment(self, session_id: str) -> None:
        session = self.enroll_sessions.pop(session_id)
        self.phone_sessions.pop(session.phone_id, None)
        session.event.set()

    def phone_session(self, phone_id: str) -> EnrollmentSession:
        session = self.phone_sessions.get(phone_id)
        if session is None or time.monotonic() >= session.expires or session.result is not None:
            raise HTTPException(404, 'Enrollment is no longer available. Start again on the PC.')
        return session

    async def create_enrollment(self, body: NewEnrollment) -> dict[str, str | int]:
        now = time.monotonic()
        for session_id in [sid for sid, entry in self.enroll_sessions.items() if now >= entry.expires]:
            self.remove_enrollment(session_id)
        if len(self.enroll_sessions) >= MAX_ENROLL_SESSIONS:
            raise HTTPException(429, 'Too many enrollment sessions.')
        mac = bytes.fromhex(body.mac.replace(':', ''))
        if not any(mac) or mac[0] & 1:
            raise HTTPException(422, 'Enter a unicast Ethernet MAC address.')

        session_id, phone_id = secrets.token_urlsafe(24), secrets.token_urlsafe(24)
        session = EnrollmentSession(
            phone_id=phone_id,
            pc_name=body.pc_name,
            mac=body.mac.lower(),
            challenge=secrets.token_bytes(32),
            expires=now + ENROLL_TTL,
        )
        self.enroll_sessions[session_id] = self.phone_sessions[phone_id] = session
        return {
            'session_id': session_id,
            'enroll_url': f'{ORIGIN}/enroll?s={phone_id}',
            'expires_in': ENROLL_TTL,
        }

    async def enroll_page(self, s: str) -> FileResponse:
        self.phone_session(s)
        return FileResponse(STATIC_DIR / 'enroll.html')

    async def enroll_options(self, body: EnrollmentPhone) -> dict[str, Any]:
        session = self.phone_session(body.session)
        opts = generate_registration_options(
            rp_id=RP_ID,
            rp_name=RP_NAME,
            user_name=session.pc_name,
            user_id=body.session.encode('ascii'),
            challenge=session.challenge,
            authenticator_selection=AuthenticatorSelectionCriteria(
                resident_key=ResidentKeyRequirement.PREFERRED,
                user_verification=UserVerificationRequirement.REQUIRED,
            ),
            supported_pub_key_algs=[COSEAlgorithmIdentifier.ECDSA_SHA_256],
        )
        return {
            'options': json.loads(options_to_json(opts)),
            'reuse': {
                # The PC only accepts its own 32-byte unlock challenge.
                'challenge': b64url(b'\x01' + session.challenge),
                'rpId': RP_ID,
                'userVerification': 'required',
                'timeout': 60000,
            },
        }

    async def enroll_verify(self, body: EnrollFinish) -> dict[str, bool]:
        session = self.phone_session(body.session)
        try:
            v = verify_registration_response(
                credential=body.credential,
                expected_challenge=session.challenge,
                expected_rp_id=RP_ID,
                expected_origin=ORIGIN,
                require_user_verification=True,
                supported_pub_key_algs=[COSEAlgorithmIdentifier.ECDSA_SHA_256],
            )
            spki = spki_from_cose(v.credential_public_key)
        except Exception as e:
            raise HTTPException(400, 'Passkey registration failed.') from e

        cred_id = b64url(v.credential_id)
        if self.store.get(cred_id):
            raise HTTPException(409, 'This credential ID is already enrolled.')
        self.complete_enrollment(
            session,
            {
                'id': cred_id,
                'cose_public_key': b64url(v.credential_public_key),
                'spki_der': b64url(spki),
                'fingerprint': fingerprint(spki),
                'created': int(time.time()),
            },
        )
        return {'ok': True}

    async def enroll_reuse(self, body: EnrollFinish) -> dict[str, bool]:
        session = self.phone_session(body.session)
        credential = self.store.get(str(body.credential.get('id', '')))
        if credential is None:
            raise HTTPException(403, 'Unknown passkey. Create a new one to enroll.')
        check_authentication(
            body.credential,
            b'\x01' + session.challenge,
            credential['cose_public_key'],
            rp_id=RP_ID,
            origin=ORIGIN,
        )
        if not self.store.credential_pcs(credential):
            credential = {**credential, 'legacy_global': True}
        self.complete_enrollment(session, credential)
        return {'ok': True}

    def complete_enrollment(self, session: EnrollmentSession, credential: dict[str, Any]) -> None:
        pcs = self.store.credential_pcs(credential)
        self.store.save({**credential, 'pcs': {**pcs, session.pc_name: session.mac}})
        session.result = {
            'credential_id': credential['id'],
            'spki_der': credential['spki_der'],
            'fingerprint': credential['fingerprint'],
        }
        self.phone_sessions.pop(session.phone_id)
        session.event.set()

    async def poll_enrollment(self, session_id: str, wait: Annotated[int, Query(ge=0, le=30)] = 0) -> dict[str, str]:
        session = self.enroll_sessions.get(session_id)
        if session is None:
            return {'status': 'expired'}
        remaining = session.expires - time.monotonic()
        if session.result is None and remaining > 0 and wait:
            with suppress(TimeoutError):
                await asyncio.wait_for(session.event.wait(), timeout=min(wait, remaining))
        if self.enroll_sessions.get(session_id) is not session:
            return {'status': 'expired'}
        if time.monotonic() >= session.expires:
            self.remove_enrollment(session_id)
            return {'status': 'expired'}
        if session.result is None:
            return {'status': 'pending'}
        self.remove_enrollment(session_id)
        return {'status': 'complete', **session.result}

    async def list_pcs(self) -> list[dict[str, str]]:
        return [{'pc_name': name} for name in sorted(self.store.pcs())]

    async def wake(self, name: str, request: Request) -> dict[str, bool]:
        if request.headers.get('origin', ORIGIN) != ORIGIN:
            raise HTTPException(403, 'Wake must come from the relay origin.')
        mac = self.store.pcs().get(name)
        if mac is None:
            raise HTTPException(404, 'Unknown PC.')
        now = time.monotonic()
        if (
            now - self.last_broadcast < WAKE_GLOBAL_COOLDOWN
            or now - self.last_wake.get(name, -float('inf')) < WAKE_PC_COOLDOWN
        ):
            raise HTTPException(429, 'Wait before sending another wake request.')
        self.last_wake[name] = self.last_broadcast = now
        try:
            send_magic_packet(mac)
        except (OSError, ValueError) as e:
            raise HTTPException(503, 'Could not send the wake packet.') from e
        return {'ok': True}

    async def create_request(self, body: NewRequest) -> dict[str, str | int]:
        self.prune()
        try:
            challenge = b64url_decode(body.challenge)
        except Exception as e:
            raise HTTPException(400, 'Challenge must be base64url.') from e
        if not 32 <= len(challenge) <= 64:
            raise HTTPException(400, 'Challenge must be 32-64 bytes.')
        # One pending request per PC; a new one replaces the old.
        for rid in [r for r, q in self.requests.items() if q.pc_name == body.pc_name]:
            self.requests.pop(rid).event.set()
        if len(self.requests) >= MAX_PENDING:
            raise HTTPException(429, 'Too many pending requests.')
        req = UnlockRequest(
            id=secrets.token_urlsafe(12),
            pc_name=body.pc_name,
            challenge=challenge,
            created=time.time(),
        )
        self.requests[req.id] = req
        return {'id': req.id, 'expires_in': REQUEST_TTL}

    async def pending(self) -> list[dict[str, Any]]:
        self.prune()
        creds = self.store.all()
        return [
            {
                'id': r.id,
                'pc_name': r.pc_name,
                'age': int(time.time() - r.created),
                'options': {
                    'challenge': b64url(r.challenge),
                    'rpId': RP_ID,
                    'timeout': 60000,
                    'userVerification': 'required',
                    'allowCredentials': [
                        {'type': 'public-key', 'id': c['id']} for c in creds if matches_pc(c, r.pc_name)
                    ],
                },
            }
            for r in sorted(self.requests.values(), key=lambda q: -q.created)
            if r.status == 'pending'
        ]

    async def submit_assertion(self, rid: str, credential: dict[str, Any]) -> dict[str, str | bool]:
        self.prune()
        req = self.requests.get(rid)
        if not req or req.status != 'pending':
            raise HTTPException(404, 'No such pending request (it may have expired).')
        cred = self.store.get(str(credential.get('id', '')))
        if not cred or not matches_pc(cred, req.pc_name):
            raise HTTPException(403, 'Unknown passkey.')
        check_authentication(credential, req.challenge, cred['cose_public_key'], rp_id=RP_ID, origin=ORIGIN)
        resp = credential['response']
        req.assertion = {
            'credential_id': cred['id'],
            'authenticator_data': resp['authenticatorData'],
            'client_data_json': resp['clientDataJSON'],
            'signature': resp['signature'],
        }
        req.status = 'approved'
        req.event.set()
        return {'ok': True, 'pc_name': req.pc_name}

    async def poll(self, rid: str, wait: int = 0) -> dict[str, Any]:
        """Long-poll used by the PC. Returns the raw assertion once approved;
        the PC must verify it itself. The assertion is handed out once.
        """
        req = self.requests.get(rid)
        if not req:
            return {'status': 'expired'}
        if req.status == 'pending' and wait > 0:
            with suppress(TimeoutError):
                await asyncio.wait_for(req.event.wait(), timeout=min(wait, 30))
        if rid not in self.requests or req.expired():
            return {'status': 'expired'}
        if req.status == 'approved':
            self.requests.pop(rid)
            return {'status': 'approved', 'assertion': req.assertion}
        return {'status': 'pending'}


async def security_headers(request: Request, call_next: Callable[[Request], Awaitable[Response]]) -> Response:
    resp = await call_next(request)
    resp.headers['Cache-Control'] = 'no-store'
    resp.headers['X-Content-Type-Options'] = 'nosniff'
    resp.headers['Referrer-Policy'] = 'no-referrer'
    resp.headers['Content-Security-Policy'] = (
        "default-src 'self'; script-src 'self'; style-src 'self'; img-src 'self' data:; frame-ancestors 'none'"
    )
    return resp


def healthz() -> dict[str, bool]:
    return {'ok': True}


def index() -> FileResponse:
    return FileResponse(STATIC_DIR / 'index.html')


def create_app() -> FastAPI:
    app = FastAPI(title='pc-unlock', docs_url=None, redoc_url=None)
    relay = Relay()
    app.middleware('http')(security_headers)
    app.add_api_route('/api/enroll/sessions', relay.create_enrollment, methods=['POST'], status_code=201)
    app.add_api_route('/enroll', relay.enroll_page, methods=['GET'])
    app.add_api_route('/api/enroll/options', relay.enroll_options, methods=['POST'])
    app.add_api_route('/api/enroll/verify', relay.enroll_verify, methods=['POST'])
    app.add_api_route('/api/enroll/reuse', relay.enroll_reuse, methods=['POST'])
    app.add_api_route('/api/enroll/sessions/{session_id}', relay.poll_enrollment, methods=['GET'])
    app.add_api_route('/api/pcs', relay.list_pcs, methods=['GET'])
    app.add_api_route('/api/pcs/{name}/wake', relay.wake, methods=['POST'], status_code=202)
    app.add_api_route('/api/unlock-requests', relay.create_request, methods=['POST'], status_code=201)
    app.add_api_route('/api/unlock-requests/pending', relay.pending, methods=['GET'])
    app.add_api_route('/api/unlock-requests/{rid}/assertion', relay.submit_assertion, methods=['POST'])
    app.add_api_route('/api/unlock-requests/{rid}', relay.poll, methods=['GET'])
    app.add_api_route('/healthz', healthz, methods=['GET'])
    app.add_api_route('/', index, methods=['GET'])
    app.add_exception_handler(HTTPException, http_error)
    app.mount('/', StaticFiles(directory=STATIC_DIR), name='static')
    return app


async def http_error(_: Request, exc: Exception) -> JSONResponse:
    if isinstance(exc, HTTPException):
        return JSONResponse({'error': exc.detail}, status_code=exc.status_code)
    return JSONResponse({'error': 'Internal relay error.'}, status_code=500)


app = create_app()
